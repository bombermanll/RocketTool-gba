public static class OriginHeartGoldText
{
    public const string MessagePath = "a/0/2/7";
    public const int SpeciesNameBank = 232;
    public const int MoveNameBank = 739;
    public const int ItemNameBank = 219;
    public const int AbilityNameBank = 711;
    public const int CategoryBank = 803;
    public const int MoveEffectBank = 738;
    public const int ItemEffectBank = 218;

    public static OriginHeartGoldDecodedNames Decode(NdsRom rom)
    {
        var banks = NarcFile.Parse(rom.ReadFile(MessagePath)).Files;
        if (banks.Count <= CategoryBank)
            throw new InvalidDataException($"消息银行数量异常：{banks.Count}。");

        var speciesCodes = DecryptBank(banks[SpeciesNameBank]);
        var moveCodes = DecryptBank(banks[MoveNameBank]);
        var itemCodes = DecryptBank(banks[ItemNameBank]);
        var abilityCodes = DecryptBank(banks[AbilityNameBank]);
        var categoryCodes = DecryptBank(banks[CategoryBank]);
        var moveEffectCodes = DecryptBank(banks[MoveEffectBank]);
        var itemEffectCodes = DecryptBank(banks[ItemEffectBank]);

        if (speciesCodes.Count < 494)
            throw new InvalidDataException($"物种名银行 232 条数异常：{speciesCodes.Count}。");
        if (speciesCodes[25] is not [2419, 869, 525])
            throw new InvalidDataException("物种名银行 232 的 ID 25 不是存档验证过的皮卡丘码点 2419,869,525。");
        if (categoryCodes.Count < 4 ||
            categoryCodes[1] is not [2524, 1266, 2603, 2221])
            throw new InvalidDataException("分类银行 803 的 ID 1 不是验证过的种子精灵码点。");

        var map = new Dictionary<int, string>();
        ApplyVanilla(map);
        var conflicts = new List<string>();
        TeachAll(map, speciesCodes, SpeciesClues, "species", conflicts);
        TeachAll(map, moveCodes, MoveClues, "move", conflicts);
        TeachAll(map, itemCodes, ItemClues, "item", conflicts);
        TeachAll(map, abilityCodes, AbilityClues, "ability", conflicts);
        ExpandUnique(map, speciesCodes, ExtraSpeciesCandidates);
        if (!map.TryGetValue(1235, out var first) || first != "妙" ||
            !map.TryGetValue(2419, out var pika) || pika != "皮")
            throw new InvalidDataException("字形表未能从本 ROM 物种名交叉验证出「妙」「皮」。");

        var unresolved = new HashSet<int>();
        return new OriginHeartGoldDecodedNames(
            DecodeTable(speciesCodes, map, unresolved, skipZero: true),
            DecodeTable(moveCodes, map, unresolved, skipZero: true),
            DecodeTable(itemCodes, map, unresolved, skipZero: false),
            DecodeTable(abilityCodes, map, unresolved, skipZero: false),
            DecodeTable(categoryCodes, map, unresolved, skipZero: true),
            DecodeTable(moveEffectCodes, map, unresolved, skipZero: true),
            DecodeTable(itemEffectCodes, map, unresolved, skipZero: true),
            map.Count,
            unresolved.Count,
            [
                "物种名来自消息银行 232，不是分类银行 803。",
                "字形表由本 ROM 物种名长度匹配交叉验证（1–493 无冲突），再用已证明字形对剩余条目做唯一候选匹配。",
                ..conflicts.Take(8).Select(text => "clue skipped: " + text)
            ]);
    }

    public static IReadOnlyList<IReadOnlyList<int>> DecryptBank(byte[] raw)
    {
        if (raw.Length < 4)
            return [];
        var count = BitConverter.ToUInt16(raw, 0);
        var names = new List<IReadOnlyList<int>>(count);
        for (var i = 0; i < count; i++)
        {
            var offset = BitConverter.ToInt32(raw, 4 + i * 8);
            var key = (0x91BD3 * (i + 1)) & 0xFFFF;
            var codes = new List<int>();
            var pos = offset;
            while (pos + 2 <= raw.Length)
            {
                var code = BitConverter.ToUInt16(raw, pos) ^ key;
                key = (key + 0x493D) & 0xFFFF;
                pos += 2;
                if (code == 0xFFFF) break;
                codes.Add(code);
            }
            names.Add(codes);
        }
        return names;
    }

    public static string DecodeCodes(IReadOnlyList<int> codes, IReadOnlyDictionary<int, string> map, ISet<int>? unresolved = null)
    {
        if (codes.Count == 0) return "";
        var text = new StringBuilder();
        foreach (var code in codes)
        {
            if (code is 0xE000 or 0x25BC) { text.Append('\n'); continue; }
            if (code is 0x25BD) { text.Append('\f'); continue; }
            if (code >= 0xFF00) continue;
            if (map.TryGetValue(code, out var ch))
            {
                text.Append(ch);
                continue;
            }
            unresolved?.Add(code);
            text.Append('�');
        }
        return text.ToString();
    }

    private static Dictionary<int, string> DecodeTable(
        IReadOnlyList<IReadOnlyList<int>> bank,
        IReadOnlyDictionary<int, string> map,
        ISet<int> unresolved,
        bool skipZero)
    {
        var table = new Dictionary<int, string>();
        for (var i = 0; i < bank.Count; i++)
        {
            if (skipZero && i == 0) continue;
            table[i] = DecodeCodes(bank[i], map, unresolved);
        }
        return table;
    }

    private static void TeachAll(
        Dictionary<int, string> map,
        IReadOnlyList<IReadOnlyList<int>> bank,
        IReadOnlyDictionary<int, string> clues,
        string label,
        List<string> conflicts)
    {
        foreach (var (id, text) in clues)
        {
            if (id < 0 || id >= bank.Count)
            {
                conflicts.Add($"{label} {id} missing");
                continue;
            }
            if (!TryTeach(map, bank[id], text))
                conflicts.Add($"{label} {id} len={bank[id].Count} clue={text}");
        }
    }

    private static bool TryTeach(Dictionary<int, string> map, IReadOnlyList<int> codes, string text)
    {
        if (codes.Count != text.Length) return false;
        for (var i = 0; i < codes.Count; i++)
        {
            var code = codes[i];
            var ch = text[i].ToString();
            if (code >= 0xE000) return false;
            if (map.TryGetValue(code, out var existing) && existing != ch)
                return false;
        }
        for (var i = 0; i < codes.Count; i++)
            map[codes[i]] = text[i].ToString();
        return true;
    }


    private static void ExpandUnique(
        Dictionary<int, string> map,
        IReadOnlyList<IReadOnlyList<int>> bank,
        IReadOnlyCollection<string> candidates)
    {
        var changed = true;
        var rounds = 0;
        while (changed && rounds < 12)
        {
            changed = false;
            rounds++;
            foreach (var codes in bank)
            {
                if (codes.Count == 0) continue;
                if (codes.All(code => code >= 0xE000 || map.ContainsKey(code))) continue;
                string? unique = null;
                var hits = 0;
                foreach (var candidate in candidates)
                {
                    if (!PatternMatches(map, codes, candidate)) continue;
                    hits++;
                    unique = candidate;
                    if (hits > 1) break;
                }
                if (hits == 1 && unique is not null && TryTeach(map, codes, unique))
                    changed = true;
            }
        }
    }

    private static bool PatternMatches(IReadOnlyDictionary<int, string> map, IReadOnlyList<int> codes, string text)
    {
        if (codes.Count != text.Length) return false;
        var proven = 0;
        for (var i = 0; i < codes.Count; i++)
        {
            var code = codes[i];
            if (code >= 0xE000) return false;
            if (!map.TryGetValue(code, out var existing)) continue;
            if (existing != text[i].ToString()) return false;
            proven++;
        }
        return proven * 2 >= codes.Count;
    }

    private static void ApplyVanilla(Dictionary<int, string> map)
    {
        const string digits = "０１２３４５６７８９";
        for (var i = 0; i < digits.Length; i++)
            map[0xA2 + i] = digits[i].ToString();
        const string upper = "ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ";
        for (var i = 0; i < upper.Length; i++)
            map[0xAC + i] = upper[i].ToString();
        const string lower = "ａｂｃｄｅｆｇｈｉｊｋｌｍｎｏｐｑｒｓｔｕｖｗｘｙｚ";
        for (var i = 0; i < lower.Length; i++)
            map[0xC6 + i] = lower[i].ToString();
        map[0xE1] = "！";
        map[0xE2] = "？";
        map[0xE3] = "、";
        map[0xE4] = "。";
        map[0xE6] = "・";
        map[0xE7] = "／";
        map[0xEC] = "（";
        map[0xED] = "）";
        map[0xF0] = "＋";
        map[0xF1] = "－";
        map[0xF4] = "＝";
        map[0xF6] = "：";
        map[0xF8] = "．";
        map[0xF9] = "，";
        // Verified from xinjin4.0.sav: General OT code 0x0399 displays as the single character “叶”.
        // This is ROM/save evidence, not an ID-based import from another profile.
        map[0x0399] = "叶";
        map[0x1BB] = "♂";
        map[0x1BC] = "♀";
    }

